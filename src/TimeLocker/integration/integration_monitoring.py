def monitor_integration_temporarily(service_manager: ServiceManager, 
                                  duration_seconds: float = 300.0) -> Dict[str, Any]:
    """
    Monitor integration for a temporary period and return results.
    
    Args:
        service_manager: ServiceManager to monitor
        duration_seconds: How long to monitor (default 5 minutes)
        
    Returns:
        Monitoring results summary
    """
    monitor = create_basic_integration_monitor(service_manager)
    
    try:
        monitor.start_monitoring()
        time.sleep(duration_seconds)
        return monitor.get_monitoring_dashboard()
    finally:
        monitor.stop_monitoring()